"""One command for every number in the paper: python reproduce.py  (run from the repo root)

1. verify.py          - input hashes + corpus, NLP, FAISS, ontology, Tables 8-9, Figs 2-3 numbers
2. recheck/run.py     - Tables 5, 6, 10, Sect. 5.7, RRF, using src/hysor_rrf.py as the reference evaluation
3. figure scripts     - regenerated into _repro/evaluation/figures/ (committed figures are not overwritten)
Writes results.json and REPORT.md. Read-only on all inputs.
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCRATCH = ROOT / "_repro"


def run(args, cwd):
    print(">>", " ".join(str(a) for a in args), flush=True)
    subprocess.run([sys.executable, *map(str, args)], cwd=cwd, check=True,
                   env={**os.environ, "PYTHONHASHSEED": "42", "CUDA_VISIBLE_DEVICES": "", "PYTHONUTF8": "1"})


def check_data():
    import csv
    bad = []
    for r in csv.DictReader(open(ROOT / "DATA_MANIFEST.csv", newline="", encoding="utf-8")):
        f = ROOT / r["path"]
        if r["kind"] != "data":
            continue
        if not f.exists():
            bad.append(f"{r['path']}: missing")
        elif f.stat().st_size < 1024 and f.read_bytes().startswith(b"version https://git-lfs"):
            bad.append(f"{r['path']}: Git LFS pointer, not the real file")
    if bad:
        sys.exit("Data files are not in place:\n  " + "\n  ".join(bad) +
                 "\nRun `git lfs install` and `git lfs pull` in this repo, then retry.")


def main():
    if sys.version_info[:2] != (3, 11):
        print(f"WARNING: Python {sys.version.split()[0]}; the pinned requirements are for Python 3.11.", flush=True)
    check_data()
    run([ROOT / "verify.py"], ROOT)
    run([ROOT / "recheck" / "run.py"], ROOT)
    shutil.rmtree(SCRATCH, ignore_errors=True)
    SCRATCH.mkdir()
    for s in ("Plot_comparison.py", "plot_hazard_analysis.py"):
        run([ROOT / "src" / "rag" / s], SCRATCH)
    write_report()


def write_report():
    v = json.loads((ROOT / "verify" / "results.json").read_text(encoding="utf-8"))
    r = json.loads((ROOT / "recheck" / "results.json").read_text(encoding="utf-8"))
    results = {
        "input_files": v["hashes"]["files"], "input_missing": v["hashes"]["missing"],
        "input_hash_mismatch": v["hashes"]["hash_mismatch"],
        "non_retrieval_claims_checked": v["claims_checked"], "non_retrieval_claims_matching": v["claims_matching"],
        "retrieval_numbers_in_paper": r["paper_numbers_checked"],
        "retrieval_checked_reference_hysor_rrf": r["checked_reference_protocol"],
        "retrieval_matching_reference_hysor_rrf": r["matches_reference_protocol"],
        "retrieval_checked_published_protocol": r["checked_published_protocol"],
        "retrieval_matching_published_protocol": r["matches_published_protocol"],
        "figures_regenerated": sorted(str(p.relative_to(ROOT)) for p in (SCRATCH / "evaluation" / "figures").glob("*")),
    }
    (ROOT / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")

    import pandas as pd
    claims = pd.read_csv(ROOT / "verify" / "claims.csv")
    L = ["# HYSOR reproduction report", "",
         "Generated by `python reproduce.py`. Paper = the submitted HySOR paper (48.pdf).", "",
         f"- Inputs: {results['input_files']} files, {len(results['input_missing'])} missing, "
         f"{len(results['input_hash_mismatch'])} with a different SHA-256 than `DATA_MANIFEST.csv`.",
         f"- Corpus / ontology / scenario / figure numbers: {results['non_retrieval_claims_matching']} of "
         f"{results['non_retrieval_claims_checked']} match.",
         f"- Retrieval numbers (Tables 5, 6, 10, Sect. 5.7, RRF): {results['retrieval_matching_reference_hysor_rrf']} of "
         f"{results['retrieval_checked_reference_hysor_rrf']} match at 3 d.p. under the `hysor_rrf.py` reference evaluation; "
         f"{results['retrieval_matching_published_protocol']} of {results['retrieval_checked_published_protocol']} under the "
         f"published `bm25_baseline.py` protocol ({results['retrieval_numbers_in_paper']} retrieval numbers in the paper). "
         "Full table: `recheck/REPORT.md`.", "",
         "## Corpus, ontology, scenario and figure numbers", "",
         "| Item | Claim | Paper | Measured | Status | Source | Note |", "|---|---|---|---|---|---|---|"]
    for c in claims.itertuples():
        note = "" if pd.isna(c.note) else str(c.note).replace("|", "/")
        L.append(f"| {c.item} | {c.claim} | {c.paper} | {c.measured} | {c.status} | {c.source} | {note} |")
    L += ["", "## Retrieval numbers", "", "See `recheck/REPORT.md`.", ""]
    (ROOT / "REPORT.md").write_text("\n".join(L), encoding="utf-8")
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
